import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';

import { queryKeys } from '@/shared/react-query/keys';
import { invalidateInventoryQueries } from '@/modules/inventory/utils/invalidateInventoryQueries';
import { notify } from '@/shared/utils/notify';
import { cancelPurchase, createPurchase, getPurchase, getPurchases, receivePurchase } from '../services/purchaseService';
import type { IPurchaseDetail, IPurchaseFilters, IReceivePurchaseDTO } from '../types';

const detailKey = (id: string) => [...queryKeys.purchases, 'detail', id] as const;

export function usePurchases(page: number, filters: IPurchaseFilters, enabled = true) {
  return useQuery({
    queryKey: [...queryKeys.purchases, 'list', page, filters],
    queryFn: () => getPurchases(page, filters),
    placeholderData: (previousData) => previousData,
    enabled,
  });
}

export function usePurchase(id: string | undefined) {
  return useQuery({
    queryKey: detailKey(id ?? ''),
    queryFn: () => getPurchase(id as string),
    enabled: Boolean(id),
  });
}

/** Refresh the lists; the detail is set from the mutation response when there is one. */
function useRefreshPurchases(id: string) {
  const queryClient = useQueryClient();

  return {
    setDetail: (purchase: IPurchaseDetail) => queryClient.setQueryData(detailKey(id), purchase),
    refreshDetail: () => queryClient.invalidateQueries({ queryKey: detailKey(id) }),
    refreshLists: () => queryClient.invalidateQueries({ queryKey: queryKeys.purchases, predicate: (query) => query.queryKey[1] !== 'detail' }),
  };
}

export function useCreatePurchase() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: createPurchase,
    async onSuccess() {
      await queryClient.invalidateQueries({ queryKey: queryKeys.purchases });
      notify.success('Pedido de compra registrado.');
    },
    // The page renders the error itself (field errors + alert); no toast here.
  });
}

export function useReceivePurchase(id: string) {
  const queryClient = useQueryClient();
  const { setDetail, refreshDetail, refreshLists } = useRefreshPurchases(id);

  return {
    refreshDetail,
    ...useMutation({
      mutationFn: (data: IReceivePurchaseDTO) => receivePurchase(id, data),
      async onSuccess(purchase) {
        setDetail(purchase);
        await Promise.all([refreshLists(), invalidateInventoryQueries(queryClient)]);
        notify.success('Recebimento registrado.');
      },
      // The modal renders the error itself.
    }),
  };
}

export function useCancelPurchase(id: string) {
  const queryClient = useQueryClient();
  const { setDetail, refreshDetail, refreshLists } = useRefreshPurchases(id);

  return {
    refreshDetail,
    ...useMutation({
      mutationFn: (reason: string) => cancelPurchase(id, reason),
      async onSuccess(purchase) {
        setDetail(purchase);
        // Cancelling also cancels the payable generated by the order.
        await Promise.all([refreshLists(), queryClient.invalidateQueries({ queryKey: queryKeys.payables })]);
        notify.success('Pedido cancelado.');
      },
      // The modal renders the error itself.
    }),
  };
}
